"""Export every artifact contract to JSON Schema, and prove the committed copy is current.

    uv run python scripts/export_schemas.py            # write config/schemas/*.json
    uv run python scripts/export_schemas.py --check    # exit 1 if the on-disk copy differs

The schemas are generated, never hand-written: a schema that drifts from its Pydantic model is a
second, wrong definition of the contract. ``--check`` is the gate — it compares what the models
produce now against what is committed, and fails on any difference, including a schema that was
deleted or an extra file nobody can trace to a model.

Exit codes: 0 no difference, 1 difference, 2 the export itself could not run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from packages.core.contracts import artifacts as artifact_models  # noqa: E402
from packages.core.contracts.base import Artifact  # noqa: E402

SCHEMA_DIR = ROOT / "config" / "schemas"


def _contracts() -> dict[str, type[Artifact]]:
    """Every concrete artifact model, keyed by its ``kind``.

    Discovered rather than listed: a new artifact added to ``contracts/artifacts.py`` appears in
    the gate without anyone remembering to register it, which is the only way a generated-schema
    gate stays true.
    """
    found: dict[str, type[Artifact]] = {}
    for name in dir(artifact_models):
        candidate = getattr(artifact_models, name)
        if (
            isinstance(candidate, type)
            and issubclass(candidate, Artifact)
            and candidate is not Artifact
            and getattr(candidate, "kind", "artifact") != "artifact"
        ):
            found[candidate.kind] = candidate
    return dict(sorted(found.items()))


def schema_for(model: type[Artifact]) -> dict[str, Any]:
    payload = model.model_json_schema()
    payload["title"] = model.__name__
    payload["$comment"] = (
        f"generated by scripts/export_schemas.py from packages.core.contracts.artifacts."
        f"{model.__name__}; do not edit"
    )
    return payload


def _serialise(payload: dict[str, Any]) -> str:
    return json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def write_schemas(directory: Path = SCHEMA_DIR) -> int:
    """Write one ``<kind>.json`` per contract. Returns the number written."""
    directory.mkdir(parents=True, exist_ok=True)
    written = 0
    for kind, model in _contracts().items():
        (directory / f"{kind}.json").write_text(_serialise(schema_for(model)), encoding="utf-8")
        written += 1
    return written


def check_schemas(directory: Path = SCHEMA_DIR) -> int:
    """0 when the committed schemas are exactly what the models produce, 1 otherwise."""
    if not directory.is_dir():
        print(f"MISSING {directory} — run without --check to generate it", file=sys.stderr)
        return 1

    expected = {f"{kind}.json": _serialise(schema_for(model)) for kind, model in _contracts().items()}
    present = {path.name for path in directory.glob("*.json")}

    problems: list[str] = []
    for name, content in expected.items():
        path = directory / name
        if not path.is_file():
            problems.append(f"missing  {name}")
            continue
        if path.read_text(encoding="utf-8") != content:
            problems.append(f"stale    {name}")
    for name in sorted(present - set(expected)):
        problems.append(f"orphaned {name} (no contract produces it)")

    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        print(
            f"\nexport_schemas: {len(problems)} problem(s); run "
            "`uv run python scripts/export_schemas.py` and commit the result",
            file=sys.stderr,
        )
        return 1
    print(f"export_schemas: {len(expected)} schema(s) current")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export artifact JSON Schemas.")
    parser.add_argument("--check", action="store_true", help="fail if the on-disk copy differs")
    parser.add_argument("--dir", default=str(SCHEMA_DIR), help="output directory")
    args = parser.parse_args(argv)

    directory = Path(args.dir).resolve()
    try:
        if args.check:
            return check_schemas(directory)
        written = write_schemas(directory)
    except Exception as exc:  # noqa: BLE001 - an export failure is a gate failure, not a crash
        print(f"export_schemas: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2
    print(f"export_schemas: wrote {written} schema(s) to {directory}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
